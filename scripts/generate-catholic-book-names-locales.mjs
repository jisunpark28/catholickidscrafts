function emit(obj, name) {
  return `export const ${name}: Readonly<Record<string, string>> = ${JSON.stringify(obj, null, 2)};\n`;
}

let out = `import type { PrayerLanguageCode } from "@/lib/prayers/prayer-languages";\n\n`;
for (const [key, value] of Object.entries(data)) {
  out += emit(value, `CATHOLIC_BOOK_NAMES_${key.toUpperCase()}`);
}
out += `\nexport const CATHOLIC_BOOK_NAMES: Record<PrayerLanguageCode, Readonly<Record<string, string>>> = {\n`;
for (const key of Object.keys(data)) {
  out += `  ${key}: CATHOLIC_BOOK_NAMES_${key.toUpperCase()},\n`;
}
out += `};\n`;

