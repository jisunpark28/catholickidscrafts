#!/usr/bin/env python3
"""Build the prayer worksheets (Little / Growing / Ready) for the /prayers carousel (US Letter).

  pip install reportlab pillow && python scripts/activities/prayers/build_prayer_sheets.py [slug ...]
  -> assets/activities/<slug>/<slug>.pdf and <slug>-color.pdf (private; served by the guarded download route)
  -> public/images/activities/<slug>/preview-bw.webp, preview-color.webp (600 x 776; needs pdftoppm)
  -> src/data/activities/<slug>.model.json (Plus editor model)
  -> src/lib/resource/prayer-sheet-list.ts and prayer-sheet-models.ts (catalog rows and model imports)
Words come from src/data/prayers/prayer-phrases.json. Rerun after changing it.
"""
from __future__ import annotations

import json
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(HERE.parent / "daily"))
sys.path.insert(0, str(HERE.parent / "new-church-year"))
from reportlab.lib.pagesizes import letter  # noqa: E402
from reportlab.pdfgen import canvas  # noqa: E402

from build_sheets import preview  # noqa: E402
from export_model import RecCanvas, default_name  # noqa: E402
from kit import ASSET_DIR, REPO, register_fonts  # noqa: E402
from prayer_sheets import all_sheets  # noqa: E402

NOTICE = "// Generated by scripts/activities/prayers/build_prayer_sheets.py. Do not edit by hand.\n"


def build(sheet: dict) -> None:
    slug = sheet["slug"]
    out = ASSET_DIR / slug
    out.mkdir(parents=True, exist_ok=True)
    for colored in (False, True):
        path = out / f"{slug}{'-color' if colored else ''}.pdf"
        c = canvas.Canvas(str(path), pagesize=letter, pageCompression=1)
        c.setTitle(f"{sheet['title']} - catholickidscrafts.com")
        c.setAuthor("Catholic Kids Crafts")
        sheet["draw"](c, colored)
        c.showPage()
        c.save()
        preview(path, slug, "color" if colored else "bw")


def record(sheet: dict, colored: bool) -> list[dict]:
    c = RecCanvas(str(Path(tempfile.gettempdir()) / "ckc-activity-rec.pdf"), pagesize=letter)
    sheet["draw"](c, colored)
    for el in c.els:
        if not el.get("group"):
            el["group"] = "Page"
    return c.els


def export(sheet: dict) -> int:
    slug = sheet["slug"]
    bw, color = record(sheet, False), record(sheet, True)
    assert len(bw) == len(color), (slug, len(bw), len(color))
    elements, counters = [], {}
    for a, b in zip(bw, color):
        assert a["kind"] == b["kind"], slug
        el = dict(a)
        el["name"] = default_name(a)
        if a.get("fill") != b.get("fill"):
            el["palette"] = {"bw": a["fill"], "color": b["fill"]}
        prefix = {"text": "t", "line": "l", "circle": "c", "rect": "r", "path": "p"}[a["kind"]]
        counters[prefix] = counters.get(prefix, 0) + 1
        el["id"] = f"{prefix}{counters[prefix]}"
        elements.append(el)
    doc = {"version": 1, "slug": slug, "title": sheet["title"], "width": 612, "height": 792, "variant": "bw", "elements": elements}
    out = REPO / "src" / "data" / "activities" / f"{slug}.model.json"
    out.write_text(json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8")
    return len(elements)


def ident(slug: str) -> str:
    return "PS_" + slug.upper().replace("-", "_")


def write_ts(sheets: list[dict]) -> None:
    rows = "\n".join(
        f'  [{json.dumps(s["slug"])}, {json.dumps(s["prayer"])}, {json.dumps(s["prayerTitle"])}, "{s["level"]}", {s["part"]}, {s["parts"]}],'
        for s in sheets
    )
    (REPO / "src" / "lib" / "resource" / "prayer-sheet-list.ts").write_text(
        NOTICE
        + "// Prayer worksheets (one row per US Letter page): slug, prayer slug, prayer title, level, part, parts.\n"
        + "// Client-safe: catalog data only.\n"
        + "export type PrayerSheetLevel = \"little\" | \"growing\" | \"ready\";\n"
        + "export type PrayerSheetRow = readonly [slug: string, prayer: string, prayerTitle: string, level: PrayerSheetLevel, part: number, parts: number];\n\n"
        + "export const PRAYER_SHEET_ROWS: readonly PrayerSheetRow[] = [\n" + rows + "\n];\n",
        encoding="utf-8",
    )
    imports = "\n".join(f'import {ident(s["slug"])} from "@/data/activities/{s["slug"]}.model.json";' for s in sheets)
    entries = "\n".join(f'  "{s["slug"]}": {ident(s["slug"])} as unknown as ActivityDoc,' for s in sheets)
    (REPO / "src" / "lib" / "resource" / "prayer-sheet-models.ts").write_text(
        NOTICE
        + "// Server-only: editor models of the prayer worksheets (imported by activity-models.ts only).\n"
        + imports + "\n"
        + 'import type { ActivityDoc } from "@/lib/resource/activity-doc";\n\n'
        + "export const PRAYER_SHEET_MODELS: Record<string, ActivityDoc> = {\n" + entries + "\n};\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    register_fonts()
    sheets = all_sheets()
    only = set(sys.argv[1:])
    for s in sheets:
        if only and s["slug"] not in only:
            continue
        build(s)
        print("built", s["slug"], export(s), "elements")
    write_ts(sheets)
